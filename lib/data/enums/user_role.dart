/// Represents the various user roles in the system.
enum UserRole {
  NULL, // No role assigned.
  ADMIN, // Administrator role.
  DRIVER, // Driver role.
  CARRIER_OWNER, // Carrier owner role.
  SUB_DRIVER, // Sub-driver role.
  MERCHANDISER, // Merchandiser role.
  DISPATCHER, // Dispatcher role.
  ROUTER, // Router role.
  LOADER // Loader role.
}
